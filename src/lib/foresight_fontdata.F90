!< foresight_fontdata, the compiled-in faces: their lookup (generated by scripts/gen_fonts.py: do not edit).
module foresight_fontdata
!< foresight_fontdata, the compiled-in faces: their lookup (generated by scripts/gen_fonts.py: do not edit).
!<
!< Faces 1-4 Liberation Sans (regular, bold, italic, bold italic), 5-8 Latin Modern Roman in the same order. A glyph is
!< found by its code point (binary search); its advance and its kerning with the next glyph are in font units of its
!< face (face_upm). The procedures are in the submodule foresight_fontdata_lookup, the only user of the face data
!< modules.
use penf, only : I4P

implicit none
private
public :: FACES
public :: face_upm, face_ascent, face_descent, face_cap_height, face_x_height
public :: glyph_index, glyph_advance, glyph_kern, glyph_outline

integer(I4P), parameter :: FACES = 8_I4P !< Compiled-in faces.

interface
   pure module function face_upm(face) result(value)
   !< Font units to the em of `face`.
   integer(I4P), intent(in) :: face  !< Face, 1 to FACES.
   integer(I4P)             :: value !< Font units.
   endfunction face_upm

   pure module function face_ascent(face) result(value)
   !< Typographic ascender of `face`.
   integer(I4P), intent(in) :: face  !< Face, 1 to FACES.
   integer(I4P)             :: value !< Font units.
   endfunction face_ascent

   pure module function face_descent(face) result(value)
   !< Typographic descender of `face` (negative).
   integer(I4P), intent(in) :: face  !< Face, 1 to FACES.
   integer(I4P)             :: value !< Font units.
   endfunction face_descent

   pure module function face_cap_height(face) result(value)
   !< Capital height of `face`.
   integer(I4P), intent(in) :: face  !< Face, 1 to FACES.
   integer(I4P)             :: value !< Font units.
   endfunction face_cap_height

   pure module function face_x_height(face) result(value)
   !< x height of `face`.
   integer(I4P), intent(in) :: face  !< Face, 1 to FACES.
   integer(I4P)             :: value !< Font units.
   endfunction face_x_height

   pure module function glyph_index(face, code) result(index)
   !< The glyph index of the code point `code` in `face` (0 if absent).
   integer(I4P), intent(in) :: face  !< Face, 1 to FACES.
   integer(I4P), intent(in) :: code  !< Unicode code point.
   integer(I4P)             :: index !< Glyph index, 0 if the face lacks it.
   endfunction glyph_index

   pure module function glyph_advance(face, index) result(advance)
   !< The advance width of glyph `index` of `face`.
   integer(I4P), intent(in) :: face    !< Face, 1 to FACES.
   integer(I4P), intent(in) :: index   !< Glyph index (glyph_index), > 0.
   integer(I4P)             :: advance !< Font units.
   endfunction glyph_advance

   pure module function glyph_kern(face, left, right) result(kern)
   !< The kerning between glyphs `left` and `right` of `face`.
   integer(I4P), intent(in) :: face  !< Face, 1 to FACES.
   integer(I4P), intent(in) :: left  !< Glyph index of the first glyph, > 0.
   integer(I4P), intent(in) :: right !< Glyph index of the second glyph, > 0.
   integer(I4P)             :: kern  !< Font units (negative: closer).
   endfunction glyph_kern

   pure module subroutine glyph_outline(face, index, ops, points)
   !< The outline of glyph `index` of `face`: its operations (0 move, 1 line, 2 quadratic, 3 cubic, 4 close) and their
   !< points (x, y pairs, font units).
   integer(I4P),              intent(in)  :: face      !< Face, 1 to FACES.
   integer(I4P),              intent(in)  :: index     !< Glyph index (glyph_index), > 0.
   integer(I4P), allocatable, intent(out) :: ops(:)    !< Operations.
   integer(I4P), allocatable, intent(out) :: points(:) !< Coordinates, x then y.
   endsubroutine glyph_outline
endinterface
endmodule foresight_fontdata
