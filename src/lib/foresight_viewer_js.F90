   write(unit, '(A)') '      if (p < self.top - 0.5 || p > self.bottom + 0.5) return;'
   write(unit, '(A)') '      line(self.yticks, self.left, p, self.left + length, p, FRAME_COLOR, 1);'
   write(unit, '(A)') '      line(self.yticks, self.right, p, self.right - length, p, FRAME_COLOR, 1);'
   write(unit, '(A)') '      if (!t.major) return;'
   write(unit, '(A)') '      label(self.yticks, self.left - GAP, p + 0.35 * fs, t, "end");'
   write(unit, '(A)') '      line(self.gridGroup, self.left, p, self.right, p, GRID_COLOR, 0.5, GRID_DASHES);'
   write(unit, '(A)') '    });'
   write(unit, '(A)') '  };'
   write(unit, '(A)') ''
   write(unit, '(A)') '  // zoom by factors (fx, fy) about the page point p'
   write(unit, '(A)') '  Panel.prototype.zoomAt = function (p, fx, fy) {'
   write(unit, '(A)') '    var c = this.unitAt(p), v = this.view;'
   write(unit, '(A)') '    this.setView({u0: c.u + (v.u0 - c.u) * fx, u1: c.u + (v.u1 - c.u) * fx,'
   write(unit, '(A)') '      v0: c.v + (v.v0 - c.v) * fy, v1: c.v + (v.v1 - c.v) * fy}, false);'
   write(unit, '(A)') '  };'
   write(unit, '(A)') ''
   write(unit, '(A)') '  // zoom to the page-pixel box between points p and q'
   write(unit, '(A)') '  Panel.prototype.zoomBox = function (p, q) {'
   write(unit, '(A)') '    var a = this.unitAt(p), b = this.unitAt(q);'
   write(unit, '(A)') '    this.setView({u0: Math.min(a.u, b.u), u1: Math.max(a.u, b.u),'
   write(unit, '(A)') '      v0: Math.min(a.v, b.v), v1: Math.max(a.v, b.v)}, true);'
   write(unit, '(A)') '  };'
   write(unit, '(A)') ''
   write(unit, '(A)') '  Panel.prototype.unzoom = function () {'
   write(unit, '(A)') '    if (this.history.length) this.setView(this.history.pop(), false);'
   write(unit, '(A)') '  };'
   write(unit, '(A)') ''
   write(unit, '(A)') '  Panel.prototype.autoscale = function () {'
   write(unit, '(A)') '    if (!this.isHome()) this.setView({u0: 0, u1: 1, v0: 0, v1: 1}, true);'
   write(unit, '(A)') '  };'
   write(unit, '(A)') ''
   write(unit, '(A)') '  Panel.prototype.toggleGrid = function () {'
   write(unit, '(A)') '    this.grid = !this.grid;'
   write(unit, '(A)') '    this.redraw();'
   write(unit, '(A)') '    this.saveState();'
   write(unit, '(A)') '  };'
   write(unit, '(A)') ''
   write(unit, '(A)') '  // zoom and grid persist in the URL hash as data values, so a reload with new data keeps the view;'
   write(unit, '(A)') '  // keys are g, x, y for the first panel, g1, x1, y1 for the second, and so on'
   write(unit, '(A)') '  Panel.prototype.state = function () {'
   write(unit, '(A)') '    var v = this.view, n = this.suffix, items = ["g" + n + "=" + (this.grid ? 1 : 0)];'
   write(unit, '(A)') '    if (!this.isHome()) {'
   write(unit, '(A)') '      items.push("x" + n + "=" + [this.x.toData(v.u0), this.x.toData(v.u1)].join(","));'
   write(unit, '(A)') '      items.push("y" + n + "=" + [this.y.toData(v.v0), this.y.toData(v.v1)].join(","));'
   write(unit, '(A)') '    }'
   write(unit, '(A)') '    return items;'
   write(unit, '(A)') '  };'
   write(unit, '(A)') ''
   write(unit, '(A)') '  Panel.prototype.saveState = function () {'
   write(unit, '(A)') '    var state = [].concat.apply([], panels.map(function (p) { return p.state(); })).join("&");'
   write(unit, '(A)') '    try {'
   write(unit, '(A)') '      history.replaceState(null, "", "#" + state);'
   write(unit, '(A)') '    } catch (e) {'
   write(unit, '(A)') '      // file:// pages may refuse history updates: a fragment-only replace is always allowed'
   write(unit, '(A)') '      location.replace("#" + state);'
   write(unit, '(A)') '    }'
   write(unit, '(A)') '  };'
   write(unit, '(A)') ''
   write(unit, '(A)') '  Panel.prototype.loadState = function () {'
   write(unit, '(A)') '    var state = {}, x, y, view, n = this.suffix;'
   write(unit, '(A)') '    location.hash.slice(1).split("&").forEach(function (item) {'
   write(unit, '(A)') '      var pair = item.split("=");'
   write(unit, '(A)') '      if (pair.length === 2) state[pair[0]] = pair[1];'
   write(unit, '(A)') '    });'
   write(unit, '(A)') '    if (state["g" + n] === "0" || state["g" + n] === "1") this.grid = state["g" + n] === "1";'
   write(unit, '(A)') '    if (state["x" + n] && state["y" + n]) {'
   write(unit, '(A)') '      x = state["x" + n].split(",").map(Number);'
   write(unit, '(A)') '      y = state["y" + n].split(",").map(Number);'
   write(unit, '(A)') '      view = {u0: this.x.toUnit(x[0]), u1: this.x.toUnit(x[1]),'
   write(unit, '(A)') '        v0: this.y.toUnit(y[0]), v1: this.y.toUnit(y[1])};'
   write(unit, '(A)') '      if ([view.u0, view.u1, view.v0, view.v1].every(isFinite)) this.view = view;'
   write(unit, '(A)') '    }'
   write(unit, '(A)') '    this.redraw();'
   write(unit, '(A)') '  };'
   write(unit, '(A)') ''
   write(unit, '(A)') '  // ---- page: overlays and input handling ----'
   write(unit, '(A)') ''
   write(unit, '(A)') '  var panels = [];'
   write(unit, '(A)') ''
   write(unit, '(A)') '  function start() {'
   write(unit, '(A)') '    var svg = document.querySelector("svg");'
   write(unit, '(A)') '    if (!svg || !svg.querySelector(".fs-axes")) return;'
   write(unit, '(A)') '    svg.querySelectorAll(".fs-axes").forEach(function (group, k) {'
   write(unit, '(A)') '      panels.push(new Panel(svg, group, k));'
   write(unit, '(A)') '    });'
   write(unit, '(A)') '    var panel = panels[0];'
   write(unit, '(A)') '    var height = Number(svg.getAttribute("height"));'
   write(unit, '(A)') '    var refresh = Number(svg.getAttribute("data-refresh") || 0);'
   write(unit, '(A)') '    var readout = element(svg, "text", {x: 4, y: height - 4, "font-size": 10, fill: "#555"});'
   write(unit, '(A)') '    var box = element(svg, "rect", {fill: "none", stroke: "#555", "stroke-dasharray": "3,3",'
   write(unit, '(A)') '      display: "none"});'
   write(unit, '(A)') '    var help = helpOverlay(svg);'
   write(unit, '(A)') '    var drag = null;'
   write(unit, '(A)') ''
   write(unit, '(A)') '    function point(evt) {'
   write(unit, '(A)') '      var p = svg.createSVGPoint();'
   write(unit, '(A)') '      p.x = evt.clientX;'
   write(unit, '(A)') '      p.y = evt.clientY;'
   write(unit, '(A)') '      return p.matrixTransform(svg.getScreenCTM().inverse());'
   write(unit, '(A)') '    }'
   write(unit, '(A)') ''
   write(unit, '(A)') '    // panel under the page point p, or null'
   write(unit, '(A)') '    function panelAt(p) {'
   write(unit, '(A)') '      for (var k = 0; k < panels.length; k++) if (panels[k].contains(p)) return panels[k];'
   write(unit, '(A)') '      return null;'
   write(unit, '(A)') '    }'
   write(unit, '(A)') ''
   write(unit, '(A)') '    function showReadout(p) {'
   write(unit, '(A)') '      var c, hit = panelAt(p);'
   write(unit, '(A)') '      if (!hit) { readout.textContent = ""; return; }'
   write(unit, '(A)') '      panel = hit;'
   write(unit, '(A)') '      c = panel.unitAt(p);'
   write(unit, '(A)') '      readout.textContent = "x = " + shortNumber(panel.x.toData(c.u)) +'
   write(unit, '(A)') '        "   y = " + shortNumber(panel.y.toData(c.v));'
   write(unit, '(A)') '    }'
   write(unit, '(A)') ''
   write(unit, '(A)') '    svg.addEventListener("contextmenu", function (evt) { evt.preventDefault(); });'
   write(unit, '(A)') '    svg.addEventListener("wheel", function (evt) {'
   write(unit, '(A)') '      var p = point(evt), f;'
   write(unit, '(A)') '      if (!panelAt(p)) return;'
   write(unit, '(A)') '      panel = panelAt(p);'
   write(unit, '(A)') '      evt.preventDefault();'
   write(unit, '(A)') '      f = evt.deltaY < 0 ? 1 / ZOOM_FACTOR : ZOOM_FACTOR;'
   write(unit, '(A)') '      panel.zoomAt(p, evt.ctrlKey ? 1 : f, evt.shiftKey ? 1 : f);'
   write(unit, '(A)') '    }, {passive: false});'
   write(unit, '(A)') '    svg.addEventListener("mousedown", function (evt) {'
   write(unit, '(A)') '      var p = point(evt);'
   write(unit, '(A)') '      if (!panelAt(p)) return;'
   write(unit, '(A)') '      panel = panelAt(p);'
   write(unit, '(A)') '      evt.preventDefault();'
   write(unit, '(A)') '      drag = {button: evt.button, start: p, view: panel.view};'
   write(unit, '(A)') '    });'
   write(unit, '(A)') '    window.addEventListener("mousemove", function (evt) {'
   write(unit, '(A)') '      var p = point(evt), v, du, dv;'
   write(unit, '(A)') '      showReadout(p);'
   write(unit, '(A)') '      if (!drag) return;'
   write(unit, '(A)') '      if (drag.button === 0) {'
   write(unit, '(A)') '        v = drag.view;'
   write(unit, '(A)') '        du = (p.x - drag.start.x) / (panel.right - panel.left) * (v.u1 - v.u0);'
   write(unit, '(A)') '        dv = (p.y - drag.start.y) / (panel.bottom - panel.top) * (v.v1 - v.v0);'
   write(unit, '(A)') '        panel.setView({u0: v.u0 - du, u1: v.u1 - du, v0: v.v0 + dv, v1: v.v1 + dv}, false);'
   write(unit, '(A)') '      } else if (drag.button === 2) {'
   write(unit, '(A)') '        box.setAttribute("x", Math.min(p.x, drag.start.x));'
   write(unit, '(A)') '        box.setAttribute("y", Math.min(p.y, drag.start.y));'
   write(unit, '(A)') '        box.setAttribute("width", Math.abs(p.x - drag.start.x));'
   write(unit, '(A)') '        box.setAttribute("height", Math.abs(p.y - drag.start.y));'
   write(unit, '(A)') '        box.setAttribute("display", "inline");'
   write(unit, '(A)') '      }'
   write(unit, '(A)') '    });'
   write(unit, '(A)') '    window.addEventListener("mouseup", function (evt) {'
   write(unit, '(A)') '      var p = point(evt);'
   write(unit, '(A)') '      if (drag && drag.button === 2) {'
   write(unit, '(A)') '        box.setAttribute("display", "none");'
   write(unit, '(A)') '        if (Math.abs(p.x - drag.start.x) >= MIN_BOX && Math.abs(p.y - drag.start.y) >= MIN_BOX) {'
   write(unit, '(A)') '          panel.zoomBox(drag.start, p);'
   write(unit, '(A)') '        }'
   write(unit, '(A)') '      }'
   write(unit, '(A)') '      drag = null;'
   write(unit, '(A)') '    });'
   write(unit, '(A)') '    document.addEventListener("keydown", function (evt) {'
   write(unit, '(A)') '      if (evt.ctrlKey || evt.metaKey || evt.altKey) return;'
   write(unit, '(A)') '      if (evt.key === "u") panel.unzoom();'
   write(unit, '(A)') '      else if (evt.key === "a") panel.autoscale();'
   write(unit, '(A)') '      else if (evt.key === "g") panel.toggleGrid();'
   write(unit, '(A)') '      else if (evt.key === "h" || evt.key === "?") {'
   write(unit, '(A)') '        help.setAttribute("display", help.getAttribute("display") === "none" ? "inline" : "none");'
   write(unit, '(A)') '      }'
   write(unit, '(A)') '    });'
   write(unit, '(A)') ''
   write(unit, '(A)') '    panels.forEach(function (p) { p.loadState(); });'
   write(unit, '(A)') '    if (refresh > 0) {'
   write(unit, '(A)') '      (function reload() {'
   write(unit, '(A)') '        setTimeout(function () { if (drag) reload(); else location.reload(); }, refresh * 1000);'
   write(unit, '(A)') '      })();'
   write(unit, '(A)') '    }'
   write(unit, '(A)') '  }'
   write(unit, '(A)') ''
   write(unit, '(A)') '  function helpOverlay(svg) {'
   write(unit, '(A)') '    var lines = ["wheel: zoom (shift: x only, ctrl: y only)", "left drag: pan",'
   write(unit, '(A)') '      "right drag: zoom box", "u: undo zoom", "a: autoscale", "g: toggle grid",'
   write(unit, '(A)') '      "h: toggle this help"];'
   write(unit, '(A)') '    var group = element(svg, "g", {display: "none"});'
   write(unit, '(A)') '    element(group, "rect", {x: 20, y: 20, width: 260, height: 16 * lines.length + 12,'
   write(unit, '(A)') '      fill: "white", stroke: "#555", opacity: 0.95});'
   write(unit, '(A)') '    lines.forEach(function (text, i) {'
   write(unit, '(A)') '      element(group, "text", {x: 30, y: 38 + 16 * i, "font-size": 12}).textContent = text;'
   write(unit, '(A)') '    });'
   write(unit, '(A)') '    return group;'
   write(unit, '(A)') '  }'
   write(unit, '(A)') ''
   write(unit, '(A)') '  start();'
   write(unit, '(A)') '})();'
   endsubroutine write_viewer_js
endmodule foresight_viewer_js
