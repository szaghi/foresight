   write(unit, '(A)') '  // minor ticks of the majors first + k * step (first * step**k on a log axis), n intervals'
   write(unit, '(A)') '  // between consecutive majors, linear in value, inside [lo, hi] and [lower, upper]'
   write(unit, '(A)') '  // (mirror of append_minors)'
   write(unit, '(A)') '  function appendMinors(ticks, first, step, logaxis, n, lo, hi, lower, upper) {'
   write(unit, '(A)') '    var a = Math.min(lo, hi), b = Math.max(lo, hi), slack = 1e-9 * (b - a), kmin, kmax, k, j;'
   write(unit, '(A)') '    var ma, mb, v;'
   write(unit, '(A)') '    if (n < 2 || !(step > 0)) return;'
   write(unit, '(A)') '    if (logaxis && (step <= 1 || first <= 0)) return;'
   write(unit, '(A)') '    if (logaxis) {'
   write(unit, '(A)') '      if (a <= 0) return;'
