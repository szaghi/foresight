   write(unit, '(A)') '          if (v < lower - slack || v > upper + slack) continue;'
   write(unit, '(A)') '        }'
   write(unit, '(A)') '        ticks.push({value: v, major: false, label: "", sup: ""});'
   write(unit, '(A)') '      }'
   write(unit, '(A)') '    }'
   write(unit, '(A)') '  }'
