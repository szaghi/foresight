   write(unit, '(A)') '      kmax = Math.ceil((Math.log10(b) - Math.log10(first)) / lf - TOL);'
   write(unit, '(A)') '    } else {'
   write(unit, '(A)') '      if (Math.max(Math.abs(a), Math.abs(b), Math.abs(first)) / step > 1e15) return;'
   write(unit, '(A)') '      kmin = Math.floor((a - first) / step + TOL) - 1;'
   write(unit, '(A)') '      kmax = Math.ceil((b - first) / step - TOL);'
   write(unit, '(A)') '    }'
   write(unit, '(A)') '    if ((kmax - kmin) * n > 10 * MAX_TICKS) return;'
   write(unit, '(A)') '    for (k = kmin; k <= kmax; k++) {'
   write(unit, '(A)') '      if (logaxis) {'
   write(unit, '(A)') '        ma = Math.pow(10, Math.log10(first) + k * Math.log10(step));'
   write(unit, '(A)') '        mb = ma * step;'
   write(unit, '(A)') '      } else {'
   write(unit, '(A)') '        ma = first + k * step;'
   write(unit, '(A)') '        mb = ma + step;'
   write(unit, '(A)') '      }'
   write(unit, '(A)') '      for (j = 1; j <= n - 1; j++) {'
   write(unit, '(A)') '        v = ma + j * (mb - ma) / n;'
   write(unit, '(A)') '        if (logaxis) {'
   write(unit, '(A)') '          if (Math.log10(v) < Math.log10(a) - TOL || Math.log10(v) > Math.log10(b) + TOL) continue;'
