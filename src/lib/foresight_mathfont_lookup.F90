!< foresight_mathfont_lookup, the glyph lookup of foresight_mathfont (generated by scripts/gen_mathfont.py: do not edit).
submodule (foresight_mathfont) foresight_mathfont_lookup
!< foresight_mathfont_lookup, the glyph lookup of foresight_mathfont (generated by scripts/gen_mathfont.py: do not edit).
use foresight_mathfont_data
use foresight_mathfont_outlines

implicit none

contains
   pure module function math_glyph(code) result(value)
   !< Binary search of the sorted codes.
   integer(I4P), intent(in) :: code  !< Code point.
   integer(I4P)             :: value !< Glyph.
   integer(I4P)             :: lo    !< Lower bound.
   integer(I4P)             :: hi    !< Upper bound.
   integer(I4P)             :: mid   !< Middle.

   value = 0_I4P
   lo = 1_I4P
   hi = MATH_GLYPHS
   do while (lo <= hi)
      mid = (lo + hi) / 2_I4P
      if (MD_CODE(mid) == code) then
         value = mid
         return
      elseif (MD_CODE(mid) < code) then
         lo = mid + 1_I4P
      else
         hi = mid - 1_I4P
      endif
   enddo
   endfunction math_glyph

   pure module function math_code(glyph) result(value)
   !< MD_CODE of the glyph, 0 out of range.
   integer(I4P), intent(in) :: glyph !< Glyph number.
   integer(I4P)             :: value !< Value.

   value = 0_I4P
   if (glyph >= 1_I4P .and. glyph <= MATH_GLYPHS) value = MD_CODE(glyph)
   endfunction math_code

   pure module function math_unicode(glyph) result(value)
   !< MD_UNICODE of the glyph, 0 out of range.
   integer(I4P), intent(in) :: glyph !< Glyph number.
   integer(I4P)             :: value !< Value.

   value = 0_I4P
   if (glyph >= 1_I4P .and. glyph <= MATH_GLYPHS) value = MD_UNICODE(glyph)
   endfunction math_unicode

   pure module function math_advance(glyph) result(value)
   !< MD_ADVANCE of the glyph, 0 out of range.
   integer(I4P), intent(in) :: glyph !< Glyph number.
   integer(I4P)             :: value !< Value.

   value = 0_I4P
   if (glyph >= 1_I4P .and. glyph <= MATH_GLYPHS) value = MD_ADVANCE(glyph)
   endfunction math_advance

   pure module function math_italic(glyph) result(value)
   !< MD_ITALIC of the glyph, 0 out of range.
   integer(I4P), intent(in) :: glyph !< Glyph number.
   integer(I4P)             :: value !< Value.

   value = 0_I4P
   if (glyph >= 1_I4P .and. glyph <= MATH_GLYPHS) value = MD_ITALIC(glyph)
   endfunction math_italic

   pure module function math_accent(glyph) result(value)
   !< MD_ACCENT of the glyph, 0 out of range.
   integer(I4P), intent(in) :: glyph !< Glyph number.
   integer(I4P)             :: value !< Value.

   value = 0_I4P
   if (glyph >= 1_I4P .and. glyph <= MATH_GLYPHS) value = MD_ACCENT(glyph)
   endfunction math_accent

   pure module function math_ymin(glyph) result(value)
   !< MD_YMIN of the glyph, 0 out of range.
   integer(I4P), intent(in) :: glyph !< Glyph number.
   integer(I4P)             :: value !< Value.

   value = 0_I4P
   if (glyph >= 1_I4P .and. glyph <= MATH_GLYPHS) value = MD_YMIN(glyph)
   endfunction math_ymin

   pure module function math_ymax(glyph) result(value)
   !< MD_YMAX of the glyph, 0 out of range.
   integer(I4P), intent(in) :: glyph !< Glyph number.
   integer(I4P)             :: value !< Value.

   value = 0_I4P
   if (glyph >= 1_I4P .and. glyph <= MATH_GLYPHS) value = MD_YMAX(glyph)
   endfunction math_ymax

   pure module function math_variant(glyph, k) result(value)
   !< MD_VAR_LIST of the glyph.
   integer(I4P), intent(in) :: glyph !< Glyph number.
   integer(I4P), intent(in) :: k     !< Variant.
   integer(I4P)             :: value !< Glyph number.

   value = 0_I4P
   if (glyph < 1_I4P .or. glyph > MATH_GLYPHS .or. k < 1_I4P) return
   if (MD_VAR_FIRST(glyph) + k - 1_I4P < MD_VAR_FIRST(glyph + 1_I4P)) &
      value = MD_VAR_LIST(MD_VAR_FIRST(glyph) + k - 1_I4P)
   endfunction math_variant

   pure module function math_script_glyph(glyph, level) result(value)
   !< MD_SSTY1, MD_SSTY2.
   integer(I4P), intent(in) :: glyph !< Glyph number.
   integer(I4P), intent(in) :: level !< Level.
   integer(I4P)             :: value !< Glyph number.

   value = glyph
   if (glyph < 1_I4P .or. glyph > MATH_GLYPHS) return
   if (level == 1_I4P .and. MD_SSTY1(glyph) > 0_I4P) value = MD_SSTY1(glyph)
   if (level >= 2_I4P .and. MD_SSTY2(glyph) > 0_I4P) value = MD_SSTY2(glyph)
   endfunction math_script_glyph

   pure module subroutine math_outline(glyph, ops, points)
   !< MD_OPS and the unpacked MD_POINTS of the glyph, element by element (nvfortran 26.9 -O2: bug 36).
   integer(I4P),              intent(in)  :: glyph     !< Glyph number.
   integer(I4P), allocatable, intent(out) :: ops(:)    !< Operations.
   integer(I4P), allocatable, intent(out) :: points(:) !< Points, x and y.
   integer(I4P)                           :: k         !< Counter.
   integer(I4P)                           :: p         !< Packed point.

   integer(I4P)                           :: g         !< Glyph in its half.

   if (glyph < 1_I4P .or. glyph > MATH_GLYPHS) then
      allocate(ops(0), points(0))
      return
   endif
   if (glyph <= MD_HALF) then
      g = glyph
      allocate(ops(MD_PATH_START1(g + 1_I4P) - MD_PATH_START1(g)))
      do k = 1_I4P, size(ops, kind=I4P)
         ops(k) = MD_OPS1(MD_PATH_START1(g) + k - 1_I4P)
      enddo
      allocate(points(2_I4P * (MD_POINT_START1(g + 1_I4P) - MD_POINT_START1(g))))
      do k = 1_I4P, size(points, kind=I4P) / 2_I4P
         p = MD_POINTS1(MD_POINT_START1(g) + k - 1_I4P)
         points(2_I4P * k - 1_I4P) = p / 32768_I4P - 16384_I4P
         points(2_I4P * k) = mod(p, 32768_I4P) - 16384_I4P
      enddo
   else
      g = glyph - MD_HALF
      allocate(ops(MD_PATH_START2(g + 1_I4P) - MD_PATH_START2(g)))
      do k = 1_I4P, size(ops, kind=I4P)
         ops(k) = MD_OPS2(MD_PATH_START2(g) + k - 1_I4P)
      enddo
      allocate(points(2_I4P * (MD_POINT_START2(g + 1_I4P) - MD_POINT_START2(g))))
      do k = 1_I4P, size(points, kind=I4P) / 2_I4P
         p = MD_POINTS2(MD_POINT_START2(g) + k - 1_I4P)
         points(2_I4P * k - 1_I4P) = p / 32768_I4P - 16384_I4P
         points(2_I4P * k) = mod(p, 32768_I4P) - 16384_I4P
      enddo
   endif
   endsubroutine math_outline
endsubmodule foresight_mathfont_lookup
