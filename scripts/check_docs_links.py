#!/usr/bin/env python3
"""check_docs_links.py [DOCS_DIR]: every link of the documentation resolves, statically (the VitePress build checks the
pages too, in CI; it needs more memory than a busy workstation spares).

Checked in every page (``*.md`` under DOCS_DIR, ``node_modules``, ``api`` and ``ford.md`` left out):

- Markdown links ``[text](target)`` and images ``![alt](target)`` to pages (``page``, ``page.md``, ``page.html``,
  ``dir/`` for ``dir/index.md``), with their anchors (``#slug``, VitePress's slugs of the target's headings), and to
  files (``/examples/x.pdf`` under ``public``, ``./report/fig.svg`` next to the page);
- ``<Plot name="N" ...>`` components: ``public/examples/N.svg`` exists (with ``svg``), else ``N.html``;
- ``<<< @/path`` includes: the file exists;
- the front matter's ``link: /page`` (the home page's cards) and HTML ``<a href="...">`` of the pages.

External links (``http``, ``https``, ``mailto``) are not fetched, links to ``/api/`` (generated by the CI) not checked. Links in code blocks are skipped. Exits 1 on a dead
link and prints it with its page and line.
"""

from __future__ import annotations

import os
import re
import sys
import unicodedata

LINK = re.compile(r"!?\[(?:[^\[\]]|\[[^\]]*\])*\]\(([^()\s]+(?:\([^()]*\))?)(?:\s+\"[^\"]*\")?\)")
PLOT = re.compile(r'<Plot\s+name="([^"]+)"([^>]*)>')
INCLUDE = re.compile(r"^<<<\s+@/(\S+?)(?:\{[^}]*\})?\s*$")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*(?:\{#([^}]+)\})?\s*$")
SPECIAL = re.compile(r"[\s~`!@#$%^&*()\-_+=\[\]{}|\\;:\"'“”‘’<>,.?/]+")


def slugify(text: str) -> str:
    """VitePress's slug of a heading (@mdit-vue/shared slugify)."""
    s = unicodedata.normalize("NFKD", text)
    s = re.sub(r"[̀-ͯ]", "", s)
    s = re.sub(r"[\u0000-\u001f]", "", s)
    s = SPECIAL.sub("-", s)
    s = re.sub(r"-{2,}", "-", s).strip("-")
    s = re.sub(r"^(\d)", r"_\1", s)
    return s.lower()


def heading_text(raw: str) -> str:
    """A heading's plain text: inline code, emphasis, links and HTML tags reduced to their text."""
    s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", raw)
    s = re.sub(r"<[^>]+>", "", s)
    s = s.replace("`", "").replace("**", "").replace("__", "")
    s = re.sub(r"(?<![\w*])\*(?!\s)([^*]+)\*", r"\1", s)
    s = s.replace("\\|", "|").replace("\\", "")
    return s


def pages(docs: str) -> list[str]:
    """The pages of the site."""
    out = []
    for root, dirs, files in os.walk(docs):
        dirs[:] = [d for d in dirs if d not in ("node_modules", ".vitepress", "public", "api")]
        out += [os.path.join(root, f) for f in files if f.endswith(".md") and f != "ford.md"]
    return sorted(out)


def lines_outside_code(path: str) -> list[tuple[int, str]]:
    """The lines of a page outside fenced code blocks, numbered."""
    out = []
    fence = None
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            m = re.match(r"^\s*(```+|~~~+)", line)
            if m:
                if fence is None:
                    fence = m.group(1)[0] * len(m.group(1))
                elif line.strip().startswith(fence):
                    fence = None
                continue
            if fence is None:
                out.append((n, line.rstrip("\n")))
    return out


def anchors(path: str, cache: dict[str, set[str]]) -> set[str]:
    """The anchors of a page: its headings' slugs (repeated ones numbered, as VitePress) and explicit ids."""
    if path in cache:
        return cache[path]
    seen: dict[str, int] = {}
    out: set[str] = set()
    for _, line in lines_outside_code(path):
        m = HEADING.match(line)
        if m:
            if m.group(3):
                out.add(m.group(3))
                continue
            slug = slugify(heading_text(m.group(2)))
            if slug in seen:
                seen[slug] += 1
                out.add(f"{slug}-{seen[slug]}")
            else:
                seen[slug] = 0
                out.add(slug)
        for i in re.findall(r'<a\s+(?:id|name)="([^"]+)"', line):
            out.add(i)
    cache[path] = out
    return out


def resolve(docs: str, page: str, target: str) -> tuple[str | None, str]:
    """The file a link names (None if it names none) and its anchor."""
    path, _, anchor = target.partition("#")
    if not path:
        return page, anchor
    path = path.split("?")[0]
    if path.startswith("/"):
        base = os.path.join(docs, path.lstrip("/"))
        public = os.path.join(docs, "public", path.lstrip("/"))
    else:
        base = os.path.normpath(os.path.join(os.path.dirname(page), path))
        # a relative link to a file of public/ (``./paper/paper.pdf`` from the home page)
        public = os.path.join(docs, "public", os.path.relpath(base, docs))
    candidates = []
    if path.endswith("/"):
        candidates.append(os.path.join(base, "index.md"))
    elif base.endswith(".html"):
        candidates.append(base[:-5] + ".md")
    elif base.endswith(".md"):
        candidates.append(base)
    else:
        candidates += [base + ".md", os.path.join(base, "index.md"), base]
    if public:
        candidates.append(public)
    for c in candidates:
        if os.path.isfile(c):
            return c, anchor
    return None, anchor


def main() -> None:
    """Check every page."""
    docs = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "docs"))
    cache: dict[str, set[str]] = {}
    dead = 0
    checked = 0
    all_pages = pages(docs)
    for page in all_pages:
        rel = os.path.relpath(page, docs)
        for n, line in lines_outside_code(page):
            text = re.sub(r"`[^`]*`", "", line)
            # the home page's front matter: `link: /page#anchor` of its hero and feature cards
            targets = LINK.findall(text) + re.findall(r"^\s*link:\s*(/\S+)\s*$", line)
            targets += re.findall(r'<a\s+href="(\.?/[^"]+|[^":]+)"', text)
            for target in targets:
                if re.match(r"^(https?:|mailto:)", target):
                    continue
                if re.match(r"^/api(/|$)", target):
                    continue  # the API pages are generated by the CI (formal generate), not committed
                checked += 1
                found, anchor = resolve(docs, page, target)
                if found is None:
                    print(f"{rel}:{n}: dead link {target}")
                    dead += 1
                elif anchor and found.endswith(".md") and anchor not in anchors(found, cache):
                    print(f"{rel}:{n}: no anchor #{anchor} in {os.path.relpath(found, docs)}")
                    dead += 1
            for name, attrs in PLOT.findall(text):
                checked += 1
                ext = ".svg" if re.search(r"\bsvg\b", attrs) else ".html"
                if not os.path.isfile(os.path.join(docs, "public", "examples", name + ext)):
                    print(f"{rel}:{n}: no plot {name}{ext}")
                    dead += 1
            m = INCLUDE.match(line.strip())
            if m:
                checked += 1
                if not os.path.isfile(os.path.join(docs, m.group(1))):
                    print(f"{rel}:{n}: no file {m.group(1)}")
                    dead += 1
    print(f"{'ok  ' if not dead else 'FAIL'} {len(all_pages)} pages, {checked} links, {dead} dead")
    sys.exit(1 if dead else 0)


if __name__ == "__main__":
    main()
